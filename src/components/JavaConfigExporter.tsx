import { useState } from 'react'
import { Copy, Check, Download, X, FileCode } from 'lucide-react'
import { useParams } from '../stores/paramStore'

interface JavaConfigExporterProps {
  isOpen: boolean
  onClose: () => void
}

export function JavaConfigExporter({ isOpen, onClose }: JavaConfigExporterProps) {
  const { values } = useParams()
  const [activeTab, setActiveTab] = useState<'phoenix6' | 'revlib' | 'constants'>('phoenix6')
  const [copied, setCopied] = useState(false)

  if (!isOpen) return null

  // Parameter extraction
  const motorType = String(values['drive.motor_drive'] || 'krakenx60')
  const gearRatio = Number(values['drive.gear_ratio_drive']) || 6.12
  const wheelDia = Number(values['drive.wheel_dia']) || 0.1016
  const wheelCirc = wheelDia * Math.PI
  const supplyCurrentLimit = Number(values['drive.current_limit_drive']) || 60
  const statorCurrentLimit = Number(values['drive.stator_current_limit']) || 80
  const driveKp = Number(values['ctrl.drive_kp']) || 0.12
  const driveKv = Number(values['ctrl.drive_kv']) || 0.12
  const maxVel = Number(values['ctrl.max_vel']) || 4.8
  const maxAcc = Number(values['ctrl.max_acc']) || 12.0
  const trackWidth = Number(values['robot.track_width']) || 0.584
  const wheelBase = Number(values['robot.wheel_base']) || 0.584
  const massKg = Number(values['robot.mass']) || 54.0

  // 1. CTRE Phoenix 6 Java snippet
  const phoenix6Code = `package frc.robot.subsystems.swervedrive;

import com.ctre.phoenix6.configs.TalonFXConfiguration;
import com.ctre.phoenix6.configs.CurrentLimitsConfigs;
import com.ctre.phoenix6.configs.FeedbackConfigs;
import com.ctre.phoenix6.configs.MotorOutputConfigs;
import com.ctre.phoenix6.configs.Slot0Configs;
import com.ctre.phoenix6.signals.NeutralModeValue;

/**
 * Auto-generated by FRC Swerve Tuner
 * Motor: ${motorType.toUpperCase()} | Ratio: ${gearRatio.toFixed(2)}:1 | Wheel Dia: ${(wheelDia * 39.37).toFixed(1)} in (${wheelDia.toFixed(4)} m)
 * Target Robot Mass: ${massKg.toFixed(1)} kg | Supply Current Limit: ${supplyCurrentLimit} A
 */
public final class SwerveConfigs {

    public static TalonFXConfiguration getDriveMotorConfig() {
        TalonFXConfiguration config = new TalonFXConfiguration();

        // ── 1. Supply & Stator Current Limits (Brownout & Wheel Slip Protection) ──
        // Supply limit prevents dropping battery below 6.5V brownout under pushing load.
        // Stator limit prevents stripping wheel tread when accelerating from standstill.
        config.CurrentLimits.SupplyCurrentLimit = ${supplyCurrentLimit.toFixed(1)};
        config.CurrentLimits.SupplyCurrentLimitEnable = true;
        config.CurrentLimits.StatorCurrentLimit = ${statorCurrentLimit.toFixed(1)};
        config.CurrentLimits.StatorCurrentLimitEnable = true;

        // ── 2. Feedback & Gear Ratio Kinematics ──
        // SensorToMechanismRatio allows Phoenix 6 to report positions in mechanism rotations.
        config.Feedback.SensorToMechanismRatio = ${gearRatio.toFixed(2)};

        // ── 3. Velocity Closed-Loop PID + Feedforward (Slot 0) ──
        config.Slot0.kP = ${driveKp.toFixed(3)};
        config.Slot0.kI = 0.0;
        config.Slot0.kD = 0.0;
        config.Slot0.kV = ${driveKv.toFixed(3)}; // Volts per (mechanism rotations / second)

        // ── 4. Motor Neutral Mode ──
        config.MotorOutput.NeutralMode = NeutralModeValue.Brake;

        return config;
    }

    public static TalonFXConfiguration getSteerMotorConfig() {
        TalonFXConfiguration config = new TalonFXConfiguration();

        // Steering motors typically draw 20-30A max
        config.CurrentLimits.SupplyCurrentLimit = 35.0;
        config.CurrentLimits.SupplyCurrentLimitEnable = true;
        config.CurrentLimits.StatorCurrentLimit = 50.0;
        config.CurrentLimits.StatorCurrentLimitEnable = true;

        // Continuous wrap for swerve azimuth (0 to 1 rotation)
        config.ClosedLoopGeneral.ContinuousWrap = true;

        // Steering PID (typical azimuth gains)
        config.Slot0.kP = 40.0;
        config.Slot0.kI = 0.0;
        config.Slot0.kD = 0.5;

        config.MotorOutput.NeutralMode = NeutralModeValue.Brake;

        return config;
    }
}
`

  // 2. REVLib 2025/2026 Java snippet
  const revlibCode = `package frc.robot.subsystems.swervedrive;

import com.revrobotics.spark.SparkMax;
import com.revrobotics.spark.config.SparkMaxConfig;
import com.revrobotics.spark.config.SparkBaseConfig.IdleMode;

/**
 * Auto-generated by FRC Swerve Tuner (REVLib 2025/2026 Config Architecture)
 * Motor: REV NEO / Vortex | Ratio: ${gearRatio.toFixed(2)}:1 | Wheel Dia: ${wheelDia.toFixed(4)} m
 */
public final class RevSwerveConfigs {

    public static SparkMaxConfig getDriveConfig() {
        SparkMaxConfig config = new SparkMaxConfig();

        // ── 1. Smart Current Limits (Prevents battery sag under pushing defense) ──
        config.smartCurrentLimit(${Math.round(supplyCurrentLimit)});

        // ── 2. Idle Mode ──
        config.idleMode(IdleMode.kBrake);

        // ── 3. Position & Velocity Conversion Factors ──
        // Direct conversion to wheel meters and meters/sec
        double wheelCircumferenceMeters = ${wheelCirc.toFixed(5)};
        double positionConversion = wheelCircumferenceMeters / ${gearRatio.toFixed(2)};
        config.encoder
            .positionConversionFactor(positionConversion)
            .velocityConversionFactor(positionConversion / 60.0);

        // ── 4. Closed-Loop Velocity PIDF ──
        config.closedLoop
            .p(${driveKp.toFixed(3)})
            .i(0.0)
            .d(0.0)
            .velocityFF(${driveKv.toFixed(3)});

        return config;
    }

    public static SparkMaxConfig getSteerConfig() {
        SparkMaxConfig config = new SparkMaxConfig();

        config.smartCurrentLimit(30);
        config.idleMode(IdleMode.kBrake);

        // Azimuth steering PID
        config.closedLoop
            .p(2.5)
            .i(0.0)
            .d(0.05);

        return config;
    }
}
`

  // 3. WPILib Kinematics Constants snippet
  const constantsCode = `package frc.robot;

import edu.wpi.first.math.geometry.Translation2d;
import edu.wpi.first.math.kinematics.SwerveDriveKinematics;

/**
 * Auto-generated Physical Constants from FRC Tuner
 */
public final class DriveConstants {
    // Physical Chassis Geometry
    public static final double kTrackWidthMeters = ${trackWidth.toFixed(3)};
    public static final double kWheelBaseMeters = ${wheelBase.toFixed(3)};
    public static final double kRobotMassKg = ${massKg.toFixed(1)};
    public static final double kWheelRadiusMeters = ${(wheelDia / 2).toFixed(4)};

    // Max Teleoperated & Autonomous Limits
    public static final double kMaxSpeedMetersPerSecond = ${maxVel.toFixed(2)};
    public static final double kMaxAccelerationMetersPerSecSq = ${maxAcc.toFixed(2)};
    public static final double kMaxAngularSpeedRadPerSec = ${(maxVel / (Math.hypot(trackWidth, wheelBase) / 2)).toFixed(2)};

    // Standard 4-Module Swerve Kinematics Matrix
    public static final SwerveDriveKinematics kDriveKinematics = new SwerveDriveKinematics(
        new Translation2d( kWheelBaseMeters / 2.0,  kTrackWidthMeters / 2.0), // Front Left
        new Translation2d( kWheelBaseMeters / 2.0, -kTrackWidthMeters / 2.0), // Front Right
        new Translation2d(-kWheelBaseMeters / 2.0,  kTrackWidthMeters / 2.0), // Back Left
        new Translation2d(-kWheelBaseMeters / 2.0, -kTrackWidthMeters / 2.0)  // Back Right
    );
}
`

  const activeCode =
    activeTab === 'phoenix6' ? phoenix6Code : activeTab === 'revlib' ? revlibCode : constantsCode

  const activeFilename =
    activeTab === 'phoenix6'
      ? 'SwerveConfigs.java'
      : activeTab === 'revlib'
      ? 'RevSwerveConfigs.java'
      : 'DriveConstants.java'

  function handleCopy() {
    navigator.clipboard.writeText(activeCode)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  function handleDownload() {
    const blob = new Blob([activeCode], { type: 'text/x-java-source;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = activeFilename
    a.click()
    URL.revokeObjectURL(url)
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-in fade-in duration-150">
      <div className="w-full max-w-3xl rounded-xl border border-cyan-500/40 bg-[#0B0F19] text-zinc-200 shadow-2xl flex flex-col max-h-[85vh] overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between px-5 py-3.5 border-b border-[#1E2D4A] bg-[#070A12]">
          <div className="flex items-center gap-2.5">
            <div className="w-7 h-7 rounded-lg bg-cyan-500/15 border border-cyan-500/30 flex items-center justify-center text-cyan-400">
              <FileCode size={16} />
            </div>
            <div>
              <h2 className="text-sm font-bold font-mono tracking-wider uppercase text-white flex items-center gap-2">
                WPILib Java Configuration Exporter
                <span className="text-[9px] px-2 py-0.5 rounded-full bg-cyan-500/20 text-cyan-300 border border-cyan-500/40">
                  Ready to Compile
                </span>
              </h2>
              <p className="text-[10px] text-zinc-400 font-mono">
                Direct mapping from your tuned current limits, gear ratios, and battery sag constraints into official vendor Java code.
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded text-zinc-400 hover:text-white hover:bg-white/10 transition"
          >
            <X size={16} />
          </button>
        </div>

        {/* Tab selection toolbar */}
        <div className="flex items-center justify-between px-5 py-2.5 bg-[#0e1424] border-b border-[#1E2D4A]">
          <div className="flex gap-1.5 font-mono text-xs">
            <button
              onClick={() => setActiveTab('phoenix6')}
              className={`px-3 py-1 rounded-lg font-bold transition flex items-center gap-1.5 ${
                activeTab === 'phoenix6'
                  ? 'bg-cyan-500 text-black shadow-md'
                  : 'bg-black/40 text-zinc-400 hover:text-white border border-white/5'
              }`}
            >
              <span>CTRE Phoenix 6 (Kraken/Falcon)</span>
            </button>
            <button
              onClick={() => setActiveTab('revlib')}
              className={`px-3 py-1 rounded-lg font-bold transition flex items-center gap-1.5 ${
                activeTab === 'revlib'
                  ? 'bg-cyan-500 text-black shadow-md'
                  : 'bg-black/40 text-zinc-400 hover:text-white border border-white/5'
              }`}
            >
              <span>REVLib (NEO / SPARK MAX)</span>
            </button>
            <button
              onClick={() => setActiveTab('constants')}
              className={`px-3 py-1 rounded-lg font-bold transition flex items-center gap-1.5 ${
                activeTab === 'constants'
                  ? 'bg-cyan-500 text-black shadow-md'
                  : 'bg-black/40 text-zinc-400 hover:text-white border border-white/5'
              }`}
            >
              <span>DriveConstants.java</span>
            </button>
          </div>

          {/* Action buttons */}
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3 py-1 rounded-lg bg-white/10 hover:bg-white/20 text-white font-mono text-xs transition active:scale-95 border border-white/10"
            >
              {copied ? <Check size={13} className="text-emerald-400" /> : <Copy size={13} />}
              <span>{copied ? 'Copied!' : 'Copy Code'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-3 py-1 rounded-lg bg-emerald-600 hover:bg-emerald-500 text-white font-mono text-xs font-bold transition active:scale-95 shadow"
            >
              <Download size={13} />
              <span>Download .java</span>
            </button>
          </div>
        </div>

        {/* Code block */}
        <div className="flex-1 overflow-y-auto p-4 bg-[#050810] font-mono text-xs">
          <pre className="text-zinc-300 leading-relaxed overflow-x-auto select-all">
            <code>{activeCode}</code>
          </pre>
        </div>

        {/* Footer status summary */}
        <div className="px-5 py-2.5 bg-[#070A12] border-t border-[#1E2D4A] flex items-center justify-between text-[11px] font-mono text-zinc-400">
          <div className="flex items-center gap-3">
            <span>
              Supply Limit:{' '}
              <strong className="text-cyan-400">{supplyCurrentLimit} A</strong>
            </span>
            <span>•</span>
            <span>
              Gear Ratio:{' '}
              <strong className="text-amber-400">{gearRatio.toFixed(2)}:1</strong>
            </span>
            <span>•</span>
            <span>
              Max Vel: <strong className="text-emerald-400">{maxVel.toFixed(2)} m/s</strong>
            </span>
          </div>
          <span className="text-[10px] text-zinc-500">
            Paste directly into your team&apos;s WPILib robot project
          </span>
        </div>
      </div>
    </div>
  )
}
